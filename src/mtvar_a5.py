#!/usr/bin/env python3
"""Run preregistered A5: metric verdicts when each serving condition is scored at its assigned batch size.

The assignments are fixed in PROTOCOL.md: C1->1, C2->64, C3->64, C4->32. Pass the three J5 A100 score
files so batch-size effects are not confounded with GPU type. Output is merged into results/stats.json and
the row-level audit is written to results/validation/mtvar/a5_served_metrics.json.
"""
import argparse
import gzip
import hashlib
import itertools
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
SYSTEMS = ["gemma2_9b", "gemma3_12b", "aya_8b", "qwen25_7b", "llama31_8b"]
LPS = ["de_DE", "zh_CN", "ja_JP", "is_IS", "sw_KE", "gu_IN", "zu_ZA"]
METRICS = {"metricx": LPS, "comet22": LPS[:-1], "kiwi": LPS[:-1]}
CONDS, REPS = ["C1", "C2", "C3", "C4"], [1, 2]
BATCH = {"C1": 1, "C2": 64, "C3": 64, "C4": 32}
NPERM, ALPHA = 1000, 0.05


def load(path):
    path = Path(path)
    opener = gzip.open if path.suffix == ".gz" else open
    with opener(path, "rt") as stream:
        return [json.loads(line) for line in stream]


def run_path(directory, condition, repeat):
    for suffix in (".jsonl", ".jsonl.gz"):
        path = directory / f"{condition}_r{repeat}{suffix}"
        if path.exists():
            return path
    raise FileNotFoundError(f"missing translation run {directory}/{condition}_r{repeat}")


def metric_map(path):
    rows = load(path)
    out = {}
    for row in rows:
        key = (row["id"], row["hyp"].strip())
        if key in out:
            raise ValueError(f"duplicate metric row {key} in {path}")
        out[key] = row
    return out


_SIGNS = {}


def verdict(x, y):
    """Same fixed-seed paired sign-flip rule as src/mtvar_score.py."""
    d = np.asarray(x, float) - np.asarray(y, float)
    if d.size not in _SIGNS:
        _SIGNS[d.size] = np.random.default_rng(0).choice([-1.0, 1.0], size=(NPERM, d.size))
    observed = abs(d.mean())
    p = (1 + int((np.abs((_SIGNS[d.size] * d).mean(axis=1)) >= observed - 1e-12).sum())) / (NPERM + 1)
    return int(np.sign(round(d.mean(), 12))), bool(p < ALPHA)


def classify(verdicts):
    repeat_stable = all(verdicts[c, 1] == verdicts[c, 2] for c in CONDS)
    return {
        "any_run_differs": len(set(verdicts.values())) > 1,
        "repeat_unstable": not repeat_stable,
        "condition_sensitive": repeat_stable and len({verdicts[c, 1] for c in CONDS}) > 1,
        "condition_sign_changed": repeat_stable and len({verdicts[c, 1][0] for c in CONDS}) > 1,
    }


parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--root", default=str(ROOT / "results/validation/mtvar/translate"),
                    help="archived translation root with system/bi0/C*_r*.jsonl[.gz]")
parser.add_argument("--metrics-bs1", required=True)
parser.add_argument("--metrics-bs32", required=True)
parser.add_argument("--metrics-bs64", required=True)
parser.add_argument("--out", default=str(ROOT / "results/validation/mtvar/a5_served_metrics.json"))
parser.add_argument("--merge", action="store_true")
args = parser.parse_args()

# Score files are all generated by J5 on A100; enforce exact coverage and identity across batch sizes.
score_paths = [Path(args.metrics_bs1).resolve(), Path(args.metrics_bs32).resolve(), Path(args.metrics_bs64).resolve()]
if len({p.parent for p in score_paths}) != 1 or "j5_a100" not in str(score_paths[0].parent):
    raise SystemExit("A5 requires the three metric score files from one results/validation/mtvar/j5_a100 directory")
scores = {b: metric_map(p) for b, p in ((1, args.metrics_bs1), (32, args.metrics_bs32), (64, args.metrics_bs64))}
keysets = {b: set(rows) for b, rows in scores.items()}
if not (keysets[1] == keysets[32] == keysets[64]):
    raise SystemExit("J5 metric score files do not contain exactly the same (id, hypothesis) records")

root = Path(args.root)
translations = {}
ids_by_lp = {}
for system in SYSTEMS:
    run_dir = root / system / "bi0"
    for condition, repeat in itertools.product(CONDS, REPS):
        path = run_path(run_dir, condition, repeat)
        records = load(path)
        ids = [row["id"] for row in records]
        if len(ids) != 960 * len(LPS) or len(set(ids)) != len(ids):
            raise SystemExit(f"unexpected or duplicate translation records in {path}: {len(ids)}")
        expected = ids_by_lp or {lp: [row["id"] for row in records if row["lp"] == lp] for lp in LPS}
        if ids_by_lp:
            if any([row["id"] for row in records if row["lp"] == lp] != ids_by_lp[lp] for lp in LPS):
                raise SystemExit(f"translation IDs/order differ in {path}")
        else:
            ids_by_lp = expected
        translations[system, condition, repeat] = records

stats = {
    "mtvar.a5.scoring_batch.C1": 1,
    "mtvar.a5.scoring_batch.C2": 64,
    "mtvar.a5.scoring_batch.C3": 64,
    "mtvar.a5.scoring_batch.C4": 32,
}
details = []
for metric, supported_lps in METRICS.items():
    for lp in supported_lps:
        lp_ids = ids_by_lp[lp]
        indices = {system: {condition: {repeat: [] for repeat in REPS} for condition in CONDS} for system in SYSTEMS}
        for system in SYSTEMS:
            for condition, repeat in itertools.product(CONDS, REPS):
                by_id = {r["id"]: r for r in translations[system, condition, repeat]}
                for segment_id in lp_ids:
                    hyp = by_id[segment_id]["text"].strip()
                    score_row = scores[BATCH[condition]].get((segment_id, hyp))
                    if score_row is None:
                        raise SystemExit(f"J5 scores lack translation {system}/{condition}/r{repeat}: {segment_id}")
                    value = score_row[metric]
                    if value is None:
                        raise SystemExit(f"unexpected missing {metric} score for {segment_id}")
                    indices[system][condition][repeat].append(float(value))

        for sys_a, sys_b in itertools.combinations(SYSTEMS, 2):
            v = {(c, r): verdict(indices[sys_a][c][r], indices[sys_b][c][r])
                 for c, r in itertools.product(CONDS, REPS)}
            flags = classify(v)
            record = {"metric": metric, "lp": lp, "system_a": sys_a, "system_b": sys_b,
                      "n_segments": len(lp_ids), **flags,
                      "verdicts": {f"{c}_r{r}": {"sign": v[c, r][0], "significant": v[c, r][1]}
                                   for c, r in itertools.product(CONDS, REPS)},
                      "source_segment_ids_sha256": hashlib.sha256("\n".join(lp_ids).encode()).hexdigest()}
            details.append(record)

if len(details) != 190:
    raise SystemExit(f"A5 must contain 190 metric comparisons, got {len(details)}")
for metric in METRICS:
    group = [row for row in details if row["metric"] == metric]
    stats[f"mtvar.a5.{metric}.comparisons_n"] = len(group)
    for key in ("any_run_differs", "repeat_unstable", "condition_sensitive", "condition_sign_changed"):
        stats[f"mtvar.a5.{metric}.{key}"] = sum(row[key] for row in group)
stats["mtvar.a5.comparisons_n"] = len(details)
for key in ("any_run_differs", "repeat_unstable", "condition_sensitive", "condition_sign_changed"):
    stats[f"mtvar.a5.comparisons_{key}"] = sum(row[key] for row in details)

out = Path(args.out)
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(json.dumps({"protocol": "A5", "condition_batch_assignment": BATCH,
                           "score_files": {str(b): str(p) for b, p in
                                           ((1, args.metrics_bs1), (32, args.metrics_bs32), (64, args.metrics_bs64))},
                           "comparisons": details}, indent=2) + "\n")
print(f"A5: {stats['mtvar.a5.comparisons_condition_sensitive']} condition-sensitive, "
      f"{stats['mtvar.a5.comparisons_repeat_unstable']} repeat-unstable, of {len(details)} comparisons")
if args.merge:
    import sys
    sys.path.insert(0, str(ROOT / "src"))
    from analyze import merge
    merge(stats)
    print(f"merged {len(stats)} keys into results/stats.json")
